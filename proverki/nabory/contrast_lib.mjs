// Мерка видимости, общая для всех проверок вида. Считает не «похоже на глаз», а число:
// отношение контраста по WCAG к настоящему фону, с проходом вверх сквозь прозрачные слои.
// Пороги: обычный текст 4.5, крупный 3, граница управляющего элемента 3, рамка-разделитель 1.5.
const ПРОВЕРКА = () => {
  function разбор(c) {
    var m = String(c).match(/rgba?\(([\d.]+),\s*([\d.]+),\s*([\d.]+)(?:,\s*([\d.]+))?\)/);
    if (!m) return null;
    return { r: +m[1], g: +m[2], b: +m[3], a: m[4] === undefined ? 1 : +m[4] };
  }
  function яркость(c) {
    var f = [c.r, c.g, c.b].map(function (v) {
      v /= 255;
      return v <= 0.03928 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4);
    });
    return 0.2126 * f[0] + 0.7152 * f[1] + 0.0722 * f[2];
  }
  function контраст(a, b) {
    var l1 = яркость(a), l2 = яркость(b);
    return (Math.max(l1, l2) + 0.05) / (Math.min(l1, l2) + 0.05);
  }
  // Наложение полупрозрачного цвета на непрозрачный.
  function поверх(верх, низ) {
    if (верх.a >= 1) return верх;
    return { r: верх.r * верх.a + низ.r * (1 - верх.a),
             g: верх.g * верх.a + низ.g * (1 - верх.a),
             b: верх.b * верх.a + низ.b * (1 - верх.a), a: 1 };
  }
  // Настоящий фон под элементом: первый непрозрачный, найденный вверх по дереву, с наложением
  // всех полупрозрачных слоёв между ними.
  function фонПод(el) {
    var слои = [], n = el;
    while (n && n !== document.documentElement) {
      var c = разбор(getComputedStyle(n).backgroundColor);
      if (c && c.a > 0) { слои.push(c); if (c.a >= 1) break; }
      n = n.parentElement;
    }
    var итог = { r: 255, g: 255, b: 255, a: 1 };
    for (var i = слои.length - 1; i >= 0; i--) итог = поверх(слои[i], итог);
    return итог;
  }
  function видим(el) {
    var s = getComputedStyle(el);
    if (s.display === "none" || s.visibility === "hidden" || +s.opacity === 0) return false;
    var r = el.getBoundingClientRect();
    return r.width > 2 && r.height > 2;
  }
  function путь(el) {
    var к = el.tagName.toLowerCase();
    if (el.id) к += "#" + el.id;
    if (el.className && typeof el.className === "string") к += "." + el.className.trim().split(/\s+/).slice(0, 2).join(".");
    // Без типа и родителя «input» в отчёте ничего не говорит: искать его потом негде.
    if (el.tagName === "INPUT") к += "[" + (el.getAttribute("type") || "text") + "]";
    var р = el.parentElement;
    if (р && р.tagName !== "BODY") {
      var рк = р.tagName.toLowerCase();
      if (р.className && typeof р.className === "string") рк += "." + р.className.trim().split(/\s+/)[0];
      к = рк + " > " + к;
    }
    return к;
  }

  var текстовые = [], коробки = [], значки = [];
  document.querySelectorAll("body *").forEach(function (el) {
    if (!видим(el)) return;
    var s = getComputedStyle(el);
    var фон = фонПод(el);

    // Текст считается только у элементов, где он лежит непосредственно, а не у их обёрток.
    var свой = Array.prototype.filter.call(el.childNodes, function (n) {
      return n.nodeType === 3 && n.textContent.trim().length > 1;
    }).map(function (n) { return n.textContent.trim(); }).join(" ");
    if (свой) {
      var цвет = разбор(s.color);
      if (цвет) {
        var к = контраст(поверх(цвет, фон), фон);
        var размер = parseFloat(s.fontSize) || 16;
        var жирный = (parseInt(s.fontWeight, 10) || 400) >= 700;
        var крупный = размер >= 24 || (размер >= 18.66 && жирный);
        var порог = крупный ? 3 : 4.5;
        if (к < порог) текстовые.push({ где: путь(el), текст: свой.slice(0, 40), контраст: Math.round(к * 100) / 100, порог: порог });
      }
    }

    // Плашка, которую не отличить от того, что под ней. Ровно тот же цвет это не находка:
    // так рисуют липкие панели, которые обязаны совпадать с полотном. Ищем чуть-чуть другой.
    var своя = разбор(s.backgroundColor);
    var родФон = el.parentElement ? фонПод(el.parentElement) : { r: 255, g: 255, b: 255, a: 1 };
    if (своя && своя.a > 0) {
      var подЭл = поверх(своя, родФон);
      var тотЖе = подЭл.r === родФон.r && подЭл.g === родФон.g && подЭл.b === родФон.b;
      var кФ = контраст(подЭл, родФон);
      var естьРамка = parseFloat(s.borderTopWidth) > 0 || parseFloat(s.borderBottomWidth) > 0;
      var естьТень = s.boxShadow && s.boxShadow !== "none";
      if (кФ < 1.12 && !тотЖе && !естьРамка && !естьТень)
        коробки.push({ где: путь(el), вид: "плашка не отличается от фона", контраст: Math.round(кФ * 100) / 100 });
    }
    if (parseFloat(s.borderTopWidth) > 0) {
      var рамка = разбор(s.borderTopColor);
      if (рамка && рамка.a > 0.2) {
        // Линия лежит между двумя поверхностями: заливкой самого элемента и фоном под ним.
        // Глаз видит границу, если она отличается хотя бы от одной из них, поэтому берём лучшее
        // из двух. Считать только к своей заливке значило бы придираться к рамке, которая на
        // самом деле прекрасно видна снаружи.
        var внутри = поверх(рамка, фон), снаружи = поверх(рамка, родФон);
        var кР = Math.max(контраст(внутри, фон), контраст(снаружи, родФон));

        // Порог зависит от того, что линия означает. У поля, кнопки, переключателя, закладки и
        // чипа она показывает, где можно действовать: это граница управляющего элемента, и
        // правило требует три. У края панели, карточки или строки списка это разделитель: ему
        // довольно быть заметным. Строки списка вынесены отдельно намеренно: технически это
        // кнопки, но узнают их по тексту внутри, а не по рамке, и решётка из линий три к одному
        // на десятке строк подряд читается хуже, а не лучше.
        // Выключенное управление не обязано быть контрастным: бледная рамка и есть признак
        // того, что нажимать нечего. Требовать от неё трёх значило бы стереть эту разницу.
        if (el.matches(":disabled")) return;
        // Закладка документа сидит на серой полосе, и полоса эта своей границей уже отделена от
        // полотна; открытая закладка узнаётся тем, что вырезает нижний край полосы, а не рамкой.
        var строкаСписка = el.matches(".toc-item, .cb-item, .log-item, .dev-card, .doc-card, .doc-tab");
        var управляющий = !строкаСписка && el.matches(
          "input, select, textarea, button, .btn, .doc-tab, .tab, [role=tab], .ph-tag, .seg, .cond-badge, .insert-chip, .rt-swatch");
        var порогР = управляющий ? 3 : 1.5;
        if (кР < порогР) коробки.push({ где: путь(el),
          вид: управляющий ? "границу управляющего элемента не видно" : "разделитель не виден на фоне",
          контраст: Math.round(кР * 100) / 100, порог: порогР });
      }
    }
  });
  // Значки рисуются currentColor, то есть цветом текста своего места, но текстом не являются и
  // мимо проверки текста проходят целиком. А значок несёт смысл: галочка «документ по
  // умолчанию», точка «не сохранено», три точки меню. Для осмысленной графики порог три.
  document.querySelectorAll("svg").forEach(function (el) {
    if (!видим(el)) return;
    var s = getComputedStyle(el);
    var цвет = разбор(s.color);
    if (!цвет) return;
    var фон = фонПод(el.parentElement || el);
    var к = контраст(поверх(цвет, фон), фон);
    if (к < 3) значки.push({ где: путь(el.parentElement || el), контраст: Math.round(к * 100) / 100 });
  });

  return { текстовые: текстовые, коробки: коробки, значки: значки };
};


export { ПРОВЕРКА };
