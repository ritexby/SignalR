# Разложить составные глифы шрифта в простые очертания.
#
# Зачем. Сборщик PDF подшивает в документ только те глифы, которые встретились в тексте, и
# ссылки на составные части он тянет на один уровень. В DejaVu буква Ы составлена из Ь и палочки,
# а палочка сама составлена из латинской I; Ё составлена из Е и точек, а Е из латинской E.
# Второй уровень не подшивается, и в готовом документе Ы печатается как Ь, а Ё как две точки.
# То есть в подписанной бумаге стоят другие слова.
#
# Разложив составные глифы один раз здесь, мы избавляемся от ссылок вовсе: у каждой буквы своё
# собственное очертание, подшивать больше нечего, и от поведения сборщика ничего не зависит.
import sys
from fontTools.ttLib import TTFont
from fontTools.pens.recordingPen import DecomposingRecordingPen
from fontTools.pens.ttGlyphPen import TTGlyphPen

вход, выход = sys.argv[1], sys.argv[2]
ф = TTFont(вход)
глифы = ф["glyf"]
набор = ф.getGlyphSet()
составных = 0
for имя in ф.getGlyphOrder():
    г = глифы[имя]
    if not г.isComposite():
        continue
    составных += 1
    перо = DecomposingRecordingPen(набор)
    набор[имя].draw(перо)
    новое = TTGlyphPen(None)
    перо.replay(новое)
    глифы[имя] = новое.glyph()
ф.save(выход)
print("разложено составных глифов:", составных)

# Как пользоваться:
#   pip install fonttools
#   python3 tools/flatten_font.py исходный.ttf готовый.ttf
